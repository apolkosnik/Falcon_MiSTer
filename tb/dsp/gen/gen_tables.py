#!/usr/bin/env python3
# Generates rtl/falcon/dsp/dsp56k_tables.svh (opcode dispatch, class codes)
# and rtl/falcon/dsp/dsp56k_rom.sv (X/Y ROM contents) from Hatari's
# src/falcon/dsp_cpu.c and dsp_core.c, so the RTL decode is a mechanical copy
# of Hatari's dispatch tables.
import re, sys, os
H = sys.argv[1] if len(sys.argv) > 1 else '/home/adam/hatari/src/falcon'
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), '../../../rtl/falcon/dsp')
cpu = open(os.path.join(H, 'dsp_cpu.c')).read()
core = open(os.path.join(H, 'dsp_core.c')).read()

def table(name):
    m = re.search(r'static const dsp_emul_t ' + name + r'\[\d+\] = \{(.*?)\};', cpu, re.S)
    body = re.sub(r'/\*.*?\*/', '', m.group(1), flags=re.S)
    return [t.strip() for t in body.split(',') if t.strip()]

op8 = table('opcodes8h')
alu = table('opcodes_alu')
assert len(op8) == 512 and len(alu) == 256

classes = []
def cls(n):
    if n not in classes:
        classes.append(n)
    return classes.index(n)
for n in ['dsp_undefined'] + sorted(set(op8)):
    cls(n)

aluops = []
def aop(n):
    base = n
    if base not in aluops:
        aluops.append(base)
    return aluops.index(base)
for n in ['dsp_undefined'] + sorted(set(alu)):
    aop(n)

def cname(n):
    return 'C_' + n.replace('dsp_', '').upper()

with open(os.path.join(OUT, 'dsp56k_tables.svh'), 'w') as f:
    f.write('// Generated by tb/dsp/gen/gen_tables.py from Hatari dsp_cpu.c - do not edit\n')
    f.write('// Non-parallel instruction classes (Hatari opcodes8h[] dispatch targets)\n')
    for i, n in enumerate(classes):
        f.write('localparam [6:0] %s = 7\'d%d;\n' % (cname(n), i))
    f.write('\nfunction automatic [6:0] dsp_class8h(input [8:0] idx);\n  case (idx)\n')
    for i, n in enumerate(op8):
        if n != 'dsp_undefined':
            f.write("    9'h%03x: dsp_class8h = %s;\n" % (i, cname(n)))
    f.write('    default: dsp_class8h = C_UNDEFINED;\n  endcase\nendfunction\n\n')
    f.write('// ALU operation codes (Hatari opcodes_alu[])\n')
    # ALU ops are decoded by the core from opcode bits; emit the table of which
    # ALU slots are undefined for checking.
    und = [i for i, n in enumerate(alu) if n == 'dsp_undefined']
    f.write('function automatic alu_undefined(input [7:0] op);\n  case (op)\n')
    for i in und:
        f.write("    8'h%02x: alu_undefined = 1'b1;\n" % i)
    f.write("    default: alu_undefined = 1'b0;\n  endcase\nendfunction\n")

def romtab(name):
    m = re.search(r'static uint32_t const ' + name + r'\[0x100\] = \{(.*?)\};', core, re.S)
    body = re.sub(r'/\*.*?\*/', '', m.group(1), flags=re.S)
    v = [int(t.strip(), 16) for t in body.split(',') if t.strip()]
    assert len(v) == 256
    return v
xr = romtab('x_rom'); yr = romtab('y_rom')
with open(os.path.join(OUT, 'dsp56k_rom.sv'), 'w') as f:
    f.write('''// Generated by tb/dsp/gen/gen_tables.py from Hatari dsp_core.c - do not edit
// DSP56001 internal X ROM (mu-law / A-law tables) and Y ROM (sine table),
// 256 x 24 each, mapped at X:$0100-$01FF and Y:$0100-$01FF when OMR.DE = 1.
// Registered read (one clock latency), infers M10K ROM.
module dsp56k_rom (
    input             clk,
    input             x_en,
    input       [7:0] x_addr,
    output reg [23:0] x_q,
    input             y_en,
    input       [7:0] y_addr,
    output reg [23:0] y_q
);
    always @(posedge clk) if (x_en) begin
        case (x_addr)
''')
    for i, v in enumerate(xr):
        f.write("            8'h%02x: x_q <= 24'h%06x;\n" % (i, v))
    f.write('''        endcase
    end
    always @(posedge clk) if (y_en) begin
        case (y_addr)
''')
    for i, v in enumerate(yr):
        f.write("            8'h%02x: y_q <= 24'h%06x;\n" % (i, v))
    f.write('''        endcase
    end
endmodule
''')
print('classes:', len(classes)); print(' '.join(classes))
print('alu undefined:', [hex(i) for i,n in enumerate(alu) if n=='dsp_undefined'])

# C table for the testbench (instruction encoder self-check)
tbout = sys.argv[3] if len(sys.argv) > 3 else os.path.join(os.path.dirname(__file__), 'opcodes8h.inc')
with open(tbout, 'w') as f:
    f.write('/* Generated by gen_tables.py from Hatari dsp_cpu.c opcodes8h[] / opcodes_alu[] */\n')
    f.write('static const char *const hatari_opcodes8h[512] = {\n')
    for i in range(0, 512, 4):
        f.write('    ' + ' '.join('"%s",' % n for n in op8[i:i+4]) + '\n')
    f.write('};\nstatic const char *const hatari_opcodes_alu[256] = {\n')
    for i in range(0, 256, 4):
        f.write('    ' + ' '.join('"%s",' % n for n in alu[i:i+4]) + '\n')
    f.write('};\n')
